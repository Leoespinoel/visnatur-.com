export const productBySlug = new Map(products.map((p) => [p.slug, p]));

export function getProduct(slug: string): Product | undefined {
  return productBySlug.get(slug);
}

export function productsInCategory(category: CategorySlug): Product[] {
  return products.filter((p) => p.category === category);
}

const UNISEX_GARMENTS: Garment[] = ["cap", "sock", "hoodie", "sunglasses"];

/** Whether a piece belongs under Men or Women in the shop (unisex pieces show under both). */
export function isFor(p: Product, audience: AudienceSlug): boolean {
  const cut = p.audience ?? (UNISEX_GARMENTS.includes(p.garment) ? "unisex" : "men");
  return cut === "unisex" || cut === audience;
}

export function featuredProducts(limit = 8): Product[] {
  return products
    .filter((p) => p.featured !== undefined)
    .sort((a, b) => (a.featured ?? 99) - (b.featured ?? 99))
    .slice(0, limit);
}

export function newProducts(): Product[] {
  return products.filter((p) => p.badge === "New");
}

/** Design number, e.g. "No. 004". */
export function designNumber(p: Product): string {
  return `No. ${String(p.number).padStart(3, "0")}`;
}

/** Packshot, then the on-model shot when one has been approved, then the detail crop.
 * `?v=3` busts browser caches (Hostinger serves public files with a one-year max-age): the packshots
 * were replaced in place by the white-background versions. Bump it whenever they change again. */
export function productImages(p: Product): string[] {
  // Model shots have their own version: v4 when the knitwear was re-shot in the Quayside chino, v5 when the
  // women's Cabana shirts were re-shot in the awning stripe.
  const model = onModel.has(p.slug) ? [`/products/${p.slug}-model.jpg?v=5`] : [];
  return [`/products/${p.slug}.jpg?v=3`, ...model, `/products/${p.slug}-detail.jpg?v=3`];
}

/** Every colourway of the same pattern, in catalogue order, including `p` itself. */
export function siblingsOf(p: Product): Product[] {
  return products.filter((q) => q.family === p.family);
}

/**
 * Groups a list into families, keeping the order of first appearance. Each group holds the
 * colourways present in `list`, so a filtered or sorted list groups consistently.
 */
export function groupByFamily(list: Product[]): Product[][] {
  const groups = new Map<string, Product[]>();
  for (const p of list) {
    const g = groups.get(p.family);
    if (g) g.push(p);
    else groups.set(p.family, [p]);
  }
  return [...groups.values()];
}

/** Colourways interleaved across families (one of each design in turn), so a carousel opens on the whole range. */
export function interleaveFamilies(list: Product[]): Product[] {
  const groups = groupByFamily(list);
  const out: Product[] = [];
  for (let i = 0; out.length < list.length; i++) for (const g of groups) if (g[i]) out.push(g[i]);
  return out;
}
